func TestUpstreamLifecycle(t *testing.T) {
	e := sandbox(t)
	text := "upstream app_backend {\n\tserver 10.0.0.5:8080;\n\tkeepalive 32;\n}\n"
	if log, err := e.SaveUpstream("app_backend", text); err != nil {
		t.Fatalf("%v\n%s", err, log)
	}
	inc, _ := os.ReadFile(filepath.Join(e.NginxConfD, "hestia-nginx-tui-upstreams.conf"))
	if !strings.Contains(string(inc), e.UpstreamDir()+"/*.conf") {
		t.Fatalf("conf.d include missing: %s", inc)
	}
	// a site uses it
	s := site(t, e, "shop.example.com")
	_ = e.SaveLocations(s, "location /app/ {\n\tproxy_pass http://app_backend;\n}\n")
	ups, _ := e.ListUpstreams()
	if len(ups) != 1 || ups[0].Keepalive != 32 || len(ups[0].UsedBy) != 1 || ups[0].UsedBy[0] != "shop.example.com" {
		t.Fatalf("%+v", ups)
	}
	// invalid change is rolled back
	if _, err := e.SaveUpstream("app_backend", "upstream app_backend {\n\tserver 1.1.1.1:80;\n\tBADDIRECTIVE;\n}\n"); err == nil {
		t.Fatal("expected nginx failure")
	}
	b, _ := os.ReadFile(e.UpstreamPath("app_backend"))
	if string(b) != text {
		t.Fatalf("upstream not rolled back: %s", b)
	}
	// a brand new invalid upstream leaves no file behind
	if _, err := e.SaveUpstream("broken", "upstream broken {\n\tBADDIRECTIVE;\n}\n"); err == nil {
		t.Fatal("expected failure")
	}
	if _, err := os.Stat(e.UpstreamPath("broken")); err == nil {
		t.Fatal("failed new upstream must be removed")
	}
	if _, err := e.DeleteUpstream("app_backend"); err != nil {
		t.Fatal(err)
	}
}

