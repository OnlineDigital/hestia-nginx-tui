// sandbox builds a fake HestiaCP tree: users, templates, a v-change-web-domain-tpl
// that really substitutes templates, and an nginx whose -t fails when any
// config contains the word BADDIRECTIVE.
func sandbox(t *testing.T) *Env {
	t.Helper()
	root := t.TempDir()
	hestiaDir := filepath.Join(root, "hestia")
	home := filepath.Join(root, "home")
	state := filepath.Join(root, "etc-hnt")
	confd := filepath.Join(root, "nginx-conf.d")
	php := filepath.Join(root, "php")
	tplDir := filepath.Join(hestiaDir, "data/templates/web/nginx/php-fpm")
	for _, d := range []string{tplDir, filepath.Join(hestiaDir, "bin"), filepath.Join(hestiaDir, "conf"), filepath.Join(hestiaDir, "data/users/admin"), filepath.Join(hestiaDir, "data/users/bob"), confd, filepath.Join(php, "8.2/fpm/pool.d")} {
		if err := os.MkdirAll(d, 0o755); err != nil {
			t.Fatal(err)
		}
	}
	mustWrite := func(p, s string, mode os.FileMode) {
		if err := os.WriteFile(p, []byte(s), mode); err != nil {
			t.Fatal(err)
		}
	}
	for _, ext := range []string{"tpl", "stpl"} {
		b, _ := os.ReadFile("testdata/laravel." + ext)
		mustWrite(filepath.Join(tplDir, "laravel."+ext), string(b), 0o644)
		d, _ := os.ReadFile("testdata/default." + ext)
		mustWrite(filepath.Join(tplDir, "default."+ext), string(d), 0o644)
	}
	mustWrite(filepath.Join(hestiaDir, "conf/hestia.conf"), "WEB_SYSTEM='nginx'\nWEB_BACKEND='php-fpm'\nHOMEDIR='"+home+"'\n", 0o644)
	mustWrite(filepath.Join(hestiaDir, "data/users/admin/web.conf"),
		"DOMAIN='shop.example.com' IP='10.0.0.1' IP6='' ALIAS='www.shop.example.com' TPL='laravel' SSL='yes' BACKEND='PHP-8_2' SUSPENDED='no'\n"+
			"DOMAIN='blog.example.com' IP='10.0.0.1' ALIAS='' TPL='default' SSL='no' BACKEND='PHP-8_2' SUSPENDED='no'\n", 0o644)
	mustWrite(filepath.Join(hestiaDir, "data/users/bob/web.conf"),
		"DOMAIN='bob.test' IP='10.0.0.2' ALIAS='' TPL='laravel' SSL='no' BACKEND='PHP-8_2' SUSPENDED='no'\n", 0o644)
	mustWrite(filepath.Join(php, "8.2/fpm/pool.d/shop.example.com.conf"), "[shop.example.com]\nlisten = /run/php/php8.2-fpm-shop.example.com.sock\n", 0o644)

	changeTpl := `#!/usr/bin/env bash
user=$1; domain=$2; tpl=$3
web=` + hestiaDir + `/data/users/$user/web.conf
sed -i "/DOMAIN='$domain'/ s/TPL='[^']*'/TPL='$tpl'/" "$web"
out=` + home + `/$user/conf/web/$domain
mkdir -p "$out"
sed -e "s|%domain%|$domain|g" -e "s|%home%|` + home + `|g" -e "s|%user%|$user|g" ` + tplDir + `/$tpl.tpl > "$out/nginx.conf"
sed -e "s|%domain%|$domain|g" -e "s|%home%|` + home + `|g" -e "s|%user%|$user|g" ` + tplDir + `/$tpl.stpl > "$out/nginx.ssl.conf"
echo "Hestia: applied $tpl to $domain (restart=$4)"
`
	mustWrite(filepath.Join(hestiaDir, "bin/v-change-web-domain-tpl"), changeTpl, 0o755)
	fakeNginx := `#!/usr/bin/env bash
if [ "$1" = "-t" ]; then
  if grep -rq BADDIRECTIVE ` + state + ` 2>/dev/null; then echo 'nginx: [emerg] unknown directive "BADDIRECTIVE"' >&2; exit 1; fi
  echo "nginx: configuration file test is successful"; exit 0
fi
exit 0
`
	mustWrite(filepath.Join(root, "nginx"), fakeNginx, 0o755)

	t.Setenv("HNT_HESTIA", hestiaDir)
	t.Setenv("HNT_HOME", home)
	t.Setenv("HNT_STATE", state)
	t.Setenv("HNT_CONFD", confd)
	t.Setenv("HNT_PHP_DIR", php)
	t.Setenv("HNT_NGINX_BIN", filepath.Join(root, "nginx"))
	t.Setenv("HNT_RELOAD", "true")
	env, err := LoadEnv()
	if err != nil {
		t.Fatal(err)
	}
	return env
}

func site(t *testing.T, e *Env, domain string) Site {
	t.Helper()
	sites, err := e.LoadSites()
	if err != nil {
		t.Fatal(err)
	}
	for _, s := range sites {
		if s.Domain == domain {
			return s
		}
	}
	t.Fatalf("site %s not found", domain)
	return Site{}
}

