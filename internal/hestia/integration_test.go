func TestApplyCustomEndToEnd(t *testing.T) {
	e := sandbox(t)
	s := site(t, e, "shop.example.com")
	log, err := e.ApplyCustom(s, "laravel")
	if err != nil {
		t.Fatalf("apply failed: %v\n%s", err, log)
	}
	// generated templates
	tpl, _ := os.ReadFile(filepath.Join(e.TemplateDir(), "tui.tpl"))
	stpl, _ := os.ReadFile(filepath.Join(e.TemplateDir(), "tui.stpl"))
	inc := "include " + e.StateDir + "/sites/%domain%/locations.con[f];"
	if !strings.Contains(string(tpl), inc) || !strings.Contains(string(stpl), inc) {
		t.Fatal("both .tpl and .stpl must include the per-domain locations file")
	}
	// Hestia state switched
	if got := site(t, e, "shop.example.com").Template; got != "tui" {
		t.Fatalf("TPL is %q", got)
	}
	// the vhosts generated by (fake) Hestia point at the shared file
	for _, f := range []string{"nginx.conf", "nginx.ssl.conf"} {
		b, _ := os.ReadFile(filepath.Join(e.HomeDir, "admin/conf/web/shop.example.com", f))
		if !strings.Contains(string(b), e.StateDir+"/sites/shop.example.com/locations.con[f];") {
			t.Fatalf("%s lacks the include:\n%s", f, b)
		}
	}
	// rendered locations contain real values, no placeholders
	loc, _ := os.ReadFile(e.LocPath("shop.example.com"))
	if strings.Contains(string(loc), "%backend_lsnr%") || strings.Contains(string(loc), "%docroot%") {
		t.Fatal("placeholders left in the rendered file")
	}
	if !strings.Contains(string(loc), "fastcgi_pass unix:/run/php/php8.2-fpm-shop.example.com.sock;") {
		t.Fatalf("backend not resolved from the pool file:\n%s", loc)
	}
	if !strings.Contains(string(loc), e.HomeDir+"/admin/conf/web/shop.example.com/nginx.fastcgi_cache.conf*") {
		t.Fatalf("%s", "%home%/%user%/%domain% not rendered")
	}
	// editable source keeps the placeholders
	src, ok := e.ReadLocations("shop.example.com")
	if !ok || !strings.Contains(src, "%backend_lsnr%") {
		t.Fatal("source must keep placeholders")
	}
}

func TestEditThenApplyAndRollbackOnNginxFailure(t *testing.T) {
	e := sandbox(t)
	s := site(t, e, "shop.example.com")
	if _, err := e.ApplyCustom(s, "laravel"); err != nil {
		t.Fatal(err)
	}
	s = site(t, e, "shop.example.com")

	// good edit
	src, _ := e.ReadLocations(s.Domain)
	good := src + "\nlocation /api/ {\n\treturn 200 ok;\n}\n"
	if err := e.SaveLocations(s, good); err != nil {
		t.Fatal(err)
	}
	if _, err := e.ApplyCustom(s, "laravel"); err != nil {
		t.Fatal(err)
	}
	loc, _ := os.ReadFile(e.LocPath(s.Domain))
	if !strings.Contains(string(loc), "location /api/") {
		t.Fatal("edit not applied")
	}

	// bad edit: nginx -t fails, the previous rendered file must come back
	bad := good + "\nBADDIRECTIVE on;\n"
	if err := e.SaveLocations(s, bad); err != nil {
		t.Fatal(err)
	}
	log, err := e.ApplyCustom(s, "laravel")
	if err == nil {
		t.Fatalf("expected failure\n%s", log)
	}
	loc, _ = os.ReadFile(e.LocPath(s.Domain))
	if strings.Contains(string(loc), "BADDIRECTIVE") || !strings.Contains(string(loc), "location /api/") {
		t.Fatalf("rendered file was not rolled back:\n%s", loc)
	}
	if !strings.Contains(log, "BADDIRECTIVE") {
		t.Fatalf("nginx error should be in the log:\n%s", log)
	}
	// the user's text is not lost: it stays saved, with history
	if saved, _ := e.ReadLocations(s.Domain); !strings.Contains(saved, "BADDIRECTIVE") {
		t.Fatal("source must keep the user's text so they can fix it")
	}
	if h, _ := os.ReadDir(e.HistoryDir(s.Domain)); len(h) == 0 {
		t.Fatal("history should hold previous versions")
	}
}

