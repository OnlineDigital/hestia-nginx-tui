func TestSingleTuiTemplateForEveryBase(t *testing.T) {
	e := sandbox(t)
	shop := site(t, e, "shop.example.com") // laravel
	blog := site(t, e, "blog.example.com") // default
	if _, err := e.ApplyCustom(shop, "laravel"); err != nil {
		t.Fatal(err)
	}
	tplA, _ := os.ReadFile(filepath.Join(e.TemplateDir(), "tui.tpl"))
	stplA, _ := os.ReadFile(filepath.Join(e.TemplateDir(), "tui.stpl"))
	if _, err := e.ApplyCustom(blog, "default"); err != nil {
		t.Fatal(err)
	}
	tplB, _ := os.ReadFile(filepath.Join(e.TemplateDir(), "tui.tpl"))
	if string(tplA) != string(tplB) {
		t.Fatal("tui.tpl must be identical whatever stock template the site came from")
	}
	// the template holds the skeleton + a single include and nothing site specific
	for name, body := range map[string]string{"tpl": string(tplA), "stpl": string(stplA)} {
		if strings.Count(body, "include "+e.StateDir) != 1 {
			t.Fatalf("tui.%s must contain exactly one include of the locations file:\n%s", name, body)
		}
		for _, gone := range []string{"root ", "fastcgi_pass", "location = /favicon", "try_files"} {
			if strings.Contains(body, gone) {
				t.Fatalf("tui.%s still has site specific %q", name, gone)
			}
		}
		if !strings.Contains(body, "server_name") || !strings.Contains(body, "location /error/") {
			t.Fatalf("tui.%s lost the Hestia skeleton", name)
		}
	}
	if !strings.Contains(string(stplA), "ssl_certificate") || !strings.Contains(string(stplA), "$anti_replay") {
		t.Fatal("tui.stpl must keep the ssl skeleton")
	}
	// each site was pre-filled from the template it came from
	a, _ := e.ReadLocations("shop.example.com")
	b, _ := e.ReadLocations("blog.example.com")
	if !strings.Contains(a, "livewire") || !strings.Contains(a, "root        %docroot%/public;") {
		t.Fatalf("shop should be pre-filled from laravel:\n%s", a)
	}
	if strings.Contains(b, "livewire") || !strings.Contains(b, "root        %docroot%;") {
		t.Fatalf("blog should be pre-filled from default:\n%s", b)
	}
	if e.ReadBase("shop.example.com") != "laravel" || e.ReadBase("blog.example.com") != "default" {
		t.Fatal("seed base must be remembered")
	}
	// root is rendered per site into the shared locations file
	loc, _ := os.ReadFile(e.LocPath("shop.example.com"))
	if !strings.Contains(string(loc), e.HomeDir+"/admin/web/shop.example.com/public_html/public;") {
		t.Fatalf("root not rendered:\n%s", loc)
	}
}

func TestReseedKeepsHistory(t *testing.T) {
	e := sandbox(t)
	s := site(t, e, "shop.example.com")
	if _, err := e.ApplyCustom(s, "laravel"); err != nil {
		t.Fatal(err)
	}
	custom := "root /srv/x;\nlocation /mine/ { return 200; }\n"
	if err := e.SaveLocations(s, custom); err != nil {
		t.Fatal(err)
	}
	if err := e.ReseedLocations(s, "default"); err != nil {
		t.Fatal(err)
	}
	got, _ := e.ReadLocations(s.Domain)
	if strings.Contains(got, "/mine/") || e.ReadBase(s.Domain) != "default" {
		t.Fatal("reseed must replace the text and remember the new base")
	}
	hist, _ := os.ReadDir(e.HistoryDir(s.Domain))
	found := false
	for _, h := range hist {
		b, _ := os.ReadFile(filepath.Join(e.HistoryDir(s.Domain), h.Name()))
		if strings.Contains(string(b), "/mine/") {
			found = true
		}
	}
	if !found {
		t.Fatal("the replaced text must be kept in history/")
	}
}
